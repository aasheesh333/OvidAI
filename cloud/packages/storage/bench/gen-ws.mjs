/** The pinned npm corpus: big, real-world packages with deep small-file trees. */
const NPM_PACKAGES = [
  "express", "rxjs", "lodash", "axios", "chalk", "commander",
  "uuid", "zod", "moment", "debug", "ws", "typescript", "webpack",
];

async function genNpmWorkspace(root) {
  const app = join(root, "app");
  await writeFixed(
    join(app, "package.json"),
    JSON.stringify(
      {
        name: "bench-app",
        version: "1.0.0",
        private: true,
        dependencies: Object.fromEntries(NPM_PACKAGES.map((p) => [p, "*"])),
      },
      null,
      2,
    ),
  );
  await writeFixed(join(app, "src", "main.ts"), tokenSoup(2048));
  console.log(`[gen] npm install (${NPM_PACKAGES.join(" ")}) into app/node_modules …`);
  execFileSync(
    "npm",
    ["install", "--no-audit", "--no-fund", "--ignore-scripts", ...NPM_PACKAGES],
    { cwd: app, stdio: ["ignore", "pipe", "pipe"], timeout: 600_000, encoding: "utf8" },
  );
  console.log("[gen] npm install done");
}

/** 180 TS modules, 6-45 KB token soup. */
async function genTsModules(root) {
  const src = join(root, "app", "src");
  for (let i = 0; i < 180; i += 1) {
    await writeFixed(
      join(src, `module_${String(i).padStart(3, "0")}.ts`),
      tokenSoup(randInt(6 * 1024, 45 * 1024)),
    );
  }
  console.log("[gen] 180 TS modules written");
}

/** Git repo: 5 churn commits over the TS corpus, then `git gc --aggressive`. */
async function genGitRepo(root) {
  const app = join(root, "app");
  const git = (args) =>
    execFileSync("git", args, {
      cwd: app,
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 300_000,
      encoding: "utf8",
      env: {
        ...process.env,
        GIT_AUTHOR_NAME: "bench",
        GIT_AUTHOR_EMAIL: "bench@ovid.test",
        GIT_COMMITTER_NAME: "bench",
        GIT_COMMITTER_EMAIL: "bench@ovid.test",
        GIT_CONFIG_NOSYSTEM: "1",
      },
    });
  git(["init", "--quiet", "--initial-branch=main"]);
  git(["config", "user.name", "bench"]);
  git(["config", "user.email", "bench@ovid.test"]);
  git(["config", "core.autocrlf", "false"]);
  // The 5 commits below cross gc.auto's loose-object threshold, so each
  // commit would spawn a DETACHED `gc --auto` that races the explicit
  // `gc --aggressive` below ("gc is already running ... pid"). The fixture
  // wants exactly one gc pass; turn the automatic one off.
  git(["config", "gc.auto", "0"]);
  // 5 churn commits: each flips ~20 of the TS modules and bumps the changelog.
  const src = join(app, "src");
  for (let c = 1; c <= 5; c += 1) {
    for (let k = 0; k < 20; k += 1) {
      const idx = (c * 37 + k * 11) % 180;
      await writeFixed(
        join(src, `module_${String(idx).padStart(3, "0")}.ts`),
        tokenSoup(randInt(6 * 1024, 45 * 1024)),
      );
    }
    await writeFixed(join(app, "CHANGELOG.md"), tokenSoup(randInt(512, 2048)));
    git(["add", "-A", "."]);
    git(["commit", "--quiet", "-m", `bench churn ${c}`]);
  }
  git(["gc", "--aggressive", "--quiet"]);
  console.log("[gen] git repo: 5 churn commits + gc --aggressive done");
}

/** 24 dist chunks 150 KB-1.5 MB + matching source maps. */
async function genDist(root) {
  const dist = join(root, "app", "dist");
  for (let i = 0; i < 24; i += 1) {
    const size = randInt(150 * 1024, 1500 * 1024);
    await writeFixed(join(dist, `chunk_${String(i).padStart(2, "0")}.js`), tokenSoup(size));
    await writeFixed(
      join(dist, `chunk_${String(i).padStart(2, "0")}.js.map`),
      Buffer.from(
        JSON.stringify({
          version: 3,
          sources: [],
          names: [],
          soup: tokenSoup(Math.floor(size / 4)).toString("utf8"),
        }),
        "utf8",
      ),
    );
  }
  console.log("[gen] 24 dist chunks + source maps written");
}

/** 3 x 5 MB JSONL log files. */
async function genJsonl(root) {
  const logs = join(root, "app", "logs");
  for (let f = 0; f < 3; f += 1) {
    const lines = [];
    let written = 0;
    while (written < 5 * 1024 * 1024) {
      const line = JSON.stringify({
        t: written,
        lvl: randInt(0, 5),
        mod: TOKENS[randInt(0, TOKENS.length - 1)],
        msg: tokenSoup(randInt(120, 400)).toString("utf8"),
      });
      lines.push(line);
      written += line.length + 1;
    }
    await writeFixed(join(logs, `trace_${f}.jsonl`), Buffer.from(lines.join("\n"), "utf8"));
  }
  console.log("[gen] 3 x 5 MB JSONL logs written");
}

/** 60 JSON fixtures. */
async function genJsonFixtures(root) {
  const dir = join(root, "app", "fixtures");
  for (let i = 0; i < 60; i += 1) {
    const obj = {};
    for (let k = 0; k < randInt(4, 24); k += 1) {
      obj[`key_${k}`] = tokenSoup(randInt(64, 512)).toString("utf8");
    }
    await writeFixed(
      join(dir, `fixture_${String(i).padStart(2, "0")}.json`),
      Buffer.from(JSON.stringify(obj), "utf8"),
    );
  }
  console.log("[gen] 60 JSON fixtures written");
}

/** 2 MB CSV export. */
async function genCsv(root) {
  const rows = ["id,name,value,ts"];
  let written = 32;
  while (written < 2 * 1024 * 1024) {
    const row =
      `${randInt(0, 1_000_000)},"${tokenSoup(randInt(40, 160)).toString("utf8")}",` +
      `${randInt(0, 9999)},${BASE_MTIME_MS + randInt(0, 86_400_000)}`;
    rows.push(row);
    written += row.length + 1;
  }
  await writeFixed(join(root, "app", "data", "export.csv"), Buffer.from(rows.join("\n"), "utf8"));
  console.log("[gen] 2 MB CSV written");
}

/**
 * 27 MB uncompressed tarball of its own tree (dist+src+fixtures+data — a
 * subset, so the tarball is not part of its own input). Deterministically
 * sized: too small → padded with seeded incompressible bytes; too large →
 * truncated. Never unpacked by the bench — it is a large mixed-compressibility
 * member, exactly like the vendor tarballs real workspaces accumulate.
 */
async function genTarball(root, target = 27 * 1024 * 1024) {
  const staging = await mkdtemp(join(tmpdir(), "p7bench-tar-"));
  try {
    const input = join(staging, "in");
    await mkdir(input);
    for (const name of ["dist", "src", "fixtures", "data"]) {
      await cp(join(root, "app", name), join(input, name), { recursive: true });
    }
    const out = join(staging, "out.tar");
    execFileSync("tar", ["-cf", out, "-C", input, "."], { stdio: "ignore", timeout: 300_000 });
    let data = await readFile(out);
    if (data.length < target) {
      data = Buffer.concat([data, randomBytesDeterministic(target - data.length)]);
    } else {
      data = data.subarray(0, target);
    }
    await writeFixed(join(root, "blobs", "self-tree.tar"), data);
    console.log(`[gen] ${(data.length / 1024 / 1024).toFixed(0)} MB self-tree tarball written`);
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}

/**
 * 10 MB /dev/urandom blob — the ratio-1.0 worst case (zstd cannot touch it).
 * The ONE intentionally non-deterministic member (real entropy per spike §2);
 * sla.mjs only ever compares bytes within a single run.
 */
async function genUrandom(root) {
  const dest = join(root, "blobs", "urandom-10mb.bin");
  await mkdir(join(root, "blobs"), { recursive: true });
  const src = await openFile("/dev/urandom", "r");
  const out = await openFile(dest, "w");
  try {
    const chunk = Buffer.alloc(1024 * 1024);
    for (let i = 0; i < 10; i += 1) {
      await src.read(chunk, 0, chunk.length, null);
      await out.write(chunk);
    }
  } finally {
    await src.close();
    await out.close();
  }
  await chmod(dest, 0o644);
  await utimes(dest, FIXED_MTIME, FIXED_MTIME);
  console.log("[gen] 10 MB /dev/urandom blob written");
}

/** Copies of 3-4 host .so files (~6 MB) — real binary pages, mode 0o755. */
async function genHostSo(root) {
  const candidates = [
    "/usr/lib/x86_64-linux-gnu/libc.so.6",
    "/usr/lib/x86_64-linux-gnu/libstdc++.so.6",
    "/usr/lib/x86_64-linux-gnu/libssl.so.3",
    "/usr/lib/x86_64-linux-gnu/libcrypto.so.3",
    "/usr/lib/x86_64-linux-gnu/libzstd.so.1",
  ];
  const dir = join(root, "app", "native");
  let copied = 0;
  for (const c of candidates) {
    if (copied >= 4) break;
    try {
      await cp(c, join(dir, basename(c)));
      await chmod(join(dir, basename(c)), 0o755);
      await utimes(join(dir, basename(c)), FIXED_MTIME, FIXED_MTIME);
      copied += 1;
    } catch {
      // host file missing on this box — skip it
    }
  }
  console.log(`[gen] ${copied} host .so files copied`);
}

/** 90 synthetic @fakeorg/* packages — node_modules-shaped small-file trees. */
async function genFakeOrg(root) {
  const nm = join(root, "app", "node_modules");
  for (let i = 0; i < 90; i += 1) {
    const pkg = `pkg${String(i).padStart(2, "0")}`;
    const dir = join(nm, "@fakeorg", pkg);
    await writeFixed(
      join(dir, "package.json"),
      Buffer.from(JSON.stringify({ name: `@fakeorg/${pkg}`, version: "1.0.0", main: "index.js" })),
    );
    for (let f = 0; f < randInt(2, 6); f += 1) {
      await writeFixed(join(dir, "lib", `part_${f}.js`), tokenSoup(randInt(512, 4096)));
    }
    await writeFixed(join(dir, "index.js"), tokenSoup(randInt(256, 1024)));
    // Every 9th package carries a .bin-style symlink into its own lib.
    if (i % 9 === 0) {
      await mkdir(join(nm, ".bin"), { recursive: true });
      const link = join(nm, ".bin", `fakeorg-pkg${String(i).padStart(2, "0")}`);
      try {
        await symlink(`../@fakeorg/${pkg}/index.js`, link, "file");
      } catch {
        // exists from a prior partial run — leave it
      }
    }
  }
  console.log("[gen] 90 @fakeorg/* packages written");
}

/** --synthetic-only top-up: extra dist corpora + binary blobs to ~200 MB total. */
async function genSyntheticTopUp(root) {
  const dist = join(root, "app", "dist");
  for (let i = 24; i < 96; i += 1) {
    await writeFixed(
      join(dist, `chunk_${String(i).padStart(2, "0")}.js`),
      tokenSoup(randInt(150 * 1024, 1500 * 1024)),
    );
  }
  for (let i = 0; i < 6; i += 1) {
    await writeFixed(join(root, "blobs", `topup_${i}.bin`), randomBytesDeterministic(4 * 1024 * 1024));
  }
  console.log("[gen] synthetic top-up written (~200 MB total)");
}

// ---------------------------------------------------------------------------
// Totals walk
// ---------------------------------------------------------------------------

async function totals(dir) {
  const { lstat } = await import("node:fs/promises");
  let files = 0;
  let dirs = 0;
  let symlinks = 0;
  let bytes = 0;
  async function walk(p) {
    for (const entry of await readdir(p, { withFileTypes: true })) {
      const full = join(p, entry.name);
      const st = await lstat(full);
      if (st.isDirectory()) {
        dirs += 1;
        await walk(full);
      } else if (st.isSymbolicLink()) {
        symlinks += 1;
      } else {
        files += 1;
        bytes += st.size;
      }
    }
  }
  await walk(dir);
  return { entries: files + dirs + symlinks, files, dirs, symlinks, bytes };
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

const argv = process.argv.slice(2);
const syntheticOnly = argv.includes("--synthetic-only");
const target = argv.find((a) => !a.startsWith("--"));
if (target === undefined) {
  console.error("usage: node bench/gen-ws.mjs <targetDir> [--synthetic-only]");
  process.exit(1);
}
const root = resolve(target);
await stat(root).then(
  () => {
    throw new Error(`target ${root} already exists — remove it first (gen is not incremental)`);
  },
  () => {},
);

console.log(`[gen] target: ${root}`);
console.log(`[gen] seed: ${SEED}  fixed mtime: ${FIXED_MTIME.toISOString()}`);
await mkdir(root, { recursive: true });

if (syntheticOnly) {
  console.warn(
    "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n" +
    "!! --synthetic-only: SKIPPING the real `npm install` corpus.           !!\n" +
    "!! The synthetic corpus is inflated to ~200 MB instead, but the        !!\n" +
    "!! small-file shape of a real node_modules tree is NOT represented -  !!\n" +
    "!! treat the stage-1/3 numbers as optimistic for that member class.    !!\n" +
    "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!",
  );
} else {
  await genNpmWorkspace(root);
}

await genTsModules(root);
await genGitRepo(root);
await genDist(root);
await genJsonl(root);
await genJsonFixtures(root);
await genCsv(root);
await genFakeOrg(root);
await genHostSo(root);
await genUrandom(root);
if (syntheticOnly) {
  await genSyntheticTopUp(root);
}
await genTarball(root);

// Fixed mtime on every DIRECTORY too (stage-4 compares dir mtimes; .git's
// internal files keep their real times — git rewrites them on any touch).
{
  async function stamp(p) {
    await utimes(p, FIXED_MTIME, FIXED_MTIME).catch(() => {});
    for (const e of await readdir(p, { withFileTypes: true })) {
      if (e.isDirectory() && e.name !== ".git") await stamp(join(p, e.name));
    }
  }
  await stamp(root);
}

const t = await totals(root);
console.log("[gen] ---- fixture totals ----");
console.log(
  `[gen] entries: ${t.entries}  files: ${t.files}  dirs: ${t.dirs}  symlinks: ${t.symlinks}`,
);
console.log(`[gen] logical bytes: ${t.bytes} (${(t.bytes / 1024 / 1024).toFixed(1)} MB)`);
if (t.bytes > 200 * 1024 * 1024) {
  console.warn(
    `[gen] WARNING: fixture exceeds the 200 MB stage-4 budget (${(t.bytes / 1024 / 1024).toFixed(1)} MB)`,
  );
}
