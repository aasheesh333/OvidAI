#!/usr/bin/env node
/**
 * P7 Task 13 — deterministic SLA-bench workspace generator (spike §2).
 *
 *   node bench/gen-ws.mjs <targetDir> [--synthetic-only]
 *
 * Produces a realistic ~190 MB / ~11-12k-entry workspace for bench/sla.mjs:
 * the shape a real coding-agent workspace has after `npm install` plus a few
 * days of work - mostly small files (the 2013-Xeon spike's hard case), a few
 * large ones, symlinks, and a git repo.
 *
 * Determinism: every "random" value comes from the mulberry32 PRNG seeded
 * with the pinned constant below, and every generated entry gets a FIXED
 * mtime (one base epoch) so the tree is stable run-to-run (sla.mjs's
 * stage-4 map comparison is within one run, so this is belt-and-braces).
 * TWO deliberate exceptions, both documented in place: the /dev/urandom blob
 * (real entropy per spike §2 — the ratio-1.0 worst case) and the npm corpus
 * (registry content at install time).
 *
 * Real `npm install` (default) pulls the pinned package list into
 * app/node_modules (the realistic small-file shape + .bin symlinks).
 * --synthetic-only skips npm (registry down / offline box), inflates the
 * synthetic corpus to ~200 MB and prints a LOUD warning; sla.mjs accepts
 * either shape (the <=200 MB stage-4 budget holds for both).
 *
 * Excluded from `pnpm -r test` by design (slow, network-optional); fixture
 * output NEVER lives inside the repo (bench runs point it at /tmp).
 */

import { execFileSync } from "node:child_process";
import {
  chmod,
  cp,
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  rm,
  stat,
  symlink,
  utimes,
  writeFile,
  open as openFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";

// ---------------------------------------------------------------------------
// Determinism knobs
// ---------------------------------------------------------------------------

/** Pinned PRNG seed — change it and every generated byte changes. */
const SEED = 20261016;

/** Every generated entry carries this mtime (fixed, so runs are comparable). */
const BASE_MTIME_MS = Date.UTC(2026, 9, 16, 12, 0, 0);
const FIXED_MTIME = new Date(BASE_MTIME_MS);

/** mulberry32 — tiny, fast, deterministic. */
function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(SEED);

/** Random int in [lo, hi]. */
const randInt = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

const TOKENS = [
  "export", "const", "function", "return", "interface", "class", "await", "async",
  "import", "from", "type", "implements", "extends", "static", "readonly", "void",
  "Promise", "Record", "string", "number", "boolean", "unknown", "never", "Partial",
  "workspace", "archive", "frame", "member", "index", "stream", "reader", "digest",
  "sha256", "xxh64", "zstd", "level", "budget", "bytes", "entry", "path", "root",
];

/** Token-soup: identifier-ish text that compresses like real source but is not free. */
function tokenSoup(bytes) {
  const parts = [];
  let written = 0;
  while (written < bytes) {
    const tok = TOKENS[randInt(0, TOKENS.length - 1)];
    parts.push(tok);
    written += tok.length + 1;
  }
  return Buffer.from(parts.join(" "), "utf8").subarray(0, bytes);
}

/** Deterministic incompressible bytes (seeded PRNG — never real entropy). */
function randomBytesDeterministic(n) {
  const buf = Buffer.alloc(n);
  for (let i = 0; i + 4 <= n; i += 4) {
    buf.writeUInt32BE(Math.floor(rand() * 0xffffffff) >>> 0, i);
  }
  return buf;
}

async function writeFixed(path, data, mode = 0o644) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, data);
  await chmod(path, mode);
  await utimes(path, FIXED_MTIME, FIXED_MTIME);
}

