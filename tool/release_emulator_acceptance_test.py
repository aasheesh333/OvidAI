class ApkBindingTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.gate = load_harness()

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir="/tmp/opencode")
        self.root = Path(self.temp.name)
        self.apk = self.root / "candidate.apk"
        self.apk.write_bytes(b"ORIGINAL-INSPECTED-APK")
        self.other = self.root / "other.apk"
        self.other.write_bytes(b"UNINSPECTED-REPLACEMENT")

    def tearDown(self):
        self.temp.cleanup()

    def pinned_device(self):
        pin = self.gate.PinnedApk.open(self.apk)
        pin.create_verified_copy(self.root / "private-work")
        device = self.gate.AdbDevice(pin, "ovid34", self.root / "evidence", {})
        device._connect = lambda: None
        calls = []

        def run(arguments, **kwargs):
            calls.append(list(arguments))
            return b""

        device._run = run
        return pin, device, calls

    def test_path_replacement_after_inspection_is_refused_before_install(self):
        pin, device, calls = self.pinned_device()
        self.apk.unlink()
        self.other.rename(self.apk)
        with self.assertRaisesRegex(self.gate.HarnessError, "path/inode"):
            device.install_verified()
        self.assertFalse(any(arguments and arguments[0] == "install" for arguments in calls), calls)
        pin.close()

    def test_symlink_target_swap_after_inspection_is_refused_before_install(self):
        pin, device, calls = self.pinned_device()
        self.apk.unlink()
        self.apk.symlink_to(self.other)
        with self.assertRaisesRegex(self.gate.HarnessError, "symlink|path/inode"):
            device.install_verified()
        self.assertFalse(any(arguments and arguments[0] == "install" for arguments in calls), calls)
        pin.close()

    def test_same_inode_content_mutation_is_refused_before_install(self):
        pin, device, calls = self.pinned_device()
        self.apk.write_bytes(b"UNINSPECTED-REPLACEMENT")
        with self.assertRaisesRegex(self.gate.HarnessError, "content"):
            device.install_verified()
        self.assertFalse(any(arguments and arguments[0] == "install" for arguments in calls), calls)
        pin.close()

    def test_verified_private_copy_swap_is_also_refused(self):
        pin, device, calls = self.pinned_device()
        pin.install_path.write_bytes(b"UNINSPECTED-REPLACEMENT")
        with self.assertRaisesRegex(self.gate.HarnessError, "private copy"):
            device.install_verified()
        self.assertFalse(any(arguments and arguments[0] == "install" for arguments in calls), calls)
        pin.close()

    def test_installed_pull_is_compared_to_original_hash_not_mutable_source(self):
        pin, device, calls = self.pinned_device()

        def run(arguments, **kwargs):
            calls.append(list(arguments))
            if arguments[0] == "pull":
                Path(arguments[2]).write_bytes(b"UNINSTALLED-OTHER-BYTES")
            return b""

        device._run = run
        device._text = lambda arguments, **kwargs: "package:/data/app/ovid/base.apk\n"
        with self.assertRaisesRegex(self.gate.HarnessError, "originally inspected"):
            device.install_verified()
        self.assertTrue(any(arguments[0] == "install" for arguments in calls))
        pin.close()

    def test_private_work_symlink_swap_cannot_delete_external_canary(self):
        pin, device, calls = self.pinned_device()
        work = pin.work_path
        moved = self.root / "moved-private-work"
        work.rename(moved)
        external = self.root / "external-work"
        external.mkdir()
        canary = external / "candidate.apk"
        canary.write_bytes(b"EXTERNAL-CANARY")
        work.symlink_to(external, target_is_directory=True)
        pin.close()
        self.assertEqual(canary.read_bytes(), b"EXTERNAL-CANARY")

    def test_copy_creation_failure_cannot_follow_work_symlink(self):
        pin = self.gate.PinnedApk.open(self.apk)
        external = self.root / "external-failure-work"
        external.mkdir()
        canary = external / "candidate.apk"
        canary.write_bytes(b"EXTERNAL-FAILURE-CANARY")

        def swap_and_fail():
            work = pin.work_path
            work.rename(self.root / "moved-failure-work")
            work.symlink_to(external, target_is_directory=True)
            raise self.gate.HarnessError("injected original-path swap")

        pin.assert_original = swap_and_fail
        with self.assertRaisesRegex(self.gate.HarnessError, "injected"):
            pin.create_verified_copy(self.root / "failure-work")
        self.assertEqual(canary.read_bytes(), b"EXTERNAL-FAILURE-CANARY")
        pin.close()

    def test_initial_symlink_apk_is_never_opened_for_inspection(self):
        self.apk.unlink()
        self.apk.symlink_to(self.other)
        with self.assertRaisesRegex(self.gate.HarnessError, "symlink"):
            self.gate.PinnedApk.open(self.apk)


